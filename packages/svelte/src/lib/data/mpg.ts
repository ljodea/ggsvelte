/**
 * Bundled teaching dataset: fuel economy for 38 popular car models, 1999 and 2008.
 *
 * 234 observations from the EPA fuel-economy tables, subset to models that had
 * a new release every year between 1999 and 2008 (ggplot2's classic `mpg`
 * teaching table). Covers categorical comparison (manufacturer, class, drive,
 * fuel type, transmission) against continuous fuel economy and engine size.
 *
 * Underlying measurements are U.S. government works from fueleconomy.gov and
 * are not subject to copyright in the United States. The popular-model subset
 * and column layout match ggplot2's `mpg` (MIT). See NOTICE and MPG_CITATION.
 */

/**
 * One vehicle configuration in a model year.
 *
 * Declared as a type alias, not an interface, so the rows carry an implicit
 * index signature and can be passed to `<GGPlot data={...}>` in a consumer app.
 */
export type MpgRow = {
  /** Make, e.g. "audi". */
  manufacturer: string;
  /** Model name, e.g. "a4". */
  model: string;
  /** Engine displacement in litres. */
  displ: number;
  /** Model year: 1999 or 2008. */
  year: number;
  /** Number of cylinders. */
  cyl: number;
  /** Transmission code, e.g. "auto(l5)" or "manual(m5)". */
  trans: string;
  /** Drive train: "f" (front), "r" (rear), or "4" (4wd). */
  drv: string;
  /** City miles per gallon. */
  cty: number;
  /** Highway miles per gallon. */
  hwy: number;
  /** Fuel type code (c/d/e/p/r). */
  fl: string;
  /** Vehicle class, e.g. "compact", "suv". */
  class: string;
};

