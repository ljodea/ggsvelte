/**
 * Specimen corpora for the /themes showcase.
 *
 * These are deliberately LOCAL copies, not re-exports of the gallery examples
 * under `examples/`. The showcase used to import example corpora by name, and
 * that coupling was silently fragile: renaming an example's exported constant
 * or its field names - which happens whenever an example's dataset changes -
 * broke `check:docs` in a file nobody editing the example would think to open.
 * A theme specimen only needs a small chart of a fixed shape; it does not need
 * to be the same rows the gallery ships.
 *
 * See the follow-up issue for moving these specimens onto real historical
 * datasets, as the gallery examples now are.
 *
 * Never surface `$examples` paths in consumer-facing CopyCode snippets.
 */

