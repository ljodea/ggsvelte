/**
 * Maunga Whau (Mount Eden), Auckland, cut into three closed height rings: the
 * ground above 130, 140 and 150 metres. Each ring is one simple feature, so
 * the whole hill is three rows rather than a table of vertices.
 *
 * Rings traced by marching squares over R's `datasets::volcano` (see NOTICE),
 * read at every second grid line - 20 m spacing, the same survey as
 * examples/contour/basic. Coordinates are metres from the south-west corner,
 * already projected, which is what geom_sf expects: a GeoJSON Geometry per
 * row, in the panel's own units.
 *
 * R's own note applies: these heights should not be regarded as accurate.
 */
function poly(coords: readonly (readonly [number, number])[]): string {
  return JSON.stringify({ type: "Polygon", coordinates: [coords] });
}

